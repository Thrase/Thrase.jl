        (α) -> x3 * (1 .- α) / 2 + x4 * (1 .+ α) / 2,
        (α) -> x5 * (1 .- α) / 2 + x6 * (1 .+ α) / 2,
        (α) -> x7 * (1 .- α) / 2 + x8 * (1 .+ α) / 2]

  dex = [(α) -> x1 * (-1) / 2 + x5 * (1) / 2,
         (α) -> x2 * (-1) / 2 + x6 * (1) / 2,
         (α) -> x3 * (-1) / 2 + x7 * (1) / 2,
         (α) -> x4 * (-1) / 2 + x8 * (1) / 2,

