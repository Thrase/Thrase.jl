  (z1, z2, z3, z4, z5, z6, z7, z8) = zcorners


  # α ranges from -1 to 1 and parametrizes each edge ex(α)
  #Define 12 edges for each of x, y, z:
  ex = [(α) -> x1 * (1 .- α) / 2 + x5 * (1 .+ α) / 2,
        (α) -> x2 * (1 .- α) / 2 + x6 * (1 .+ α) / 2,
        (α) -> x3 * (1 .- α) / 2 + x7 * (1 .+ α) / 2,
        (α) -> x4 * (1 .- α) / 2 + x8 * (1 .+ α) / 2,

