        (α) -> z3 * (1 .- α) / 2 + z4 * (1 .+ α) / 2,
        (α) -> z5 * (1 .- α) / 2 + z6 * (1 .+ α) / 2,
        (α) -> z7 * (1 .- α) / 2 + z8 * (1 .+ α) / 2]

    dez = [(α) -> z1 * (-1) / 2 + z5 * (1) / 2,
        (α) -> z2 * (-1) / 2 + z6 * (1) / 2,
        (α) -> z3 * (-1) / 2 + z7 * (1) / 2,
        (α) -> z4 * (-1) / 2 + z8 * (1) / 2,

        (α) -> z1 * (-1) / 2 + z3 * (1) / 2,
        (α) -> z2 * (-1) / 2 + z4 * (1) / 2,
        (α) -> z5 * (-1) / 2 + z7 * (1) / 2,
        (α) -> z6 * (-1) / 2 + z8 * (1) / 2,

        (α) -> z1 * (-1) / 2 + z2 * (1) / 2,
        (α) -> z3 * (-1) / 2 + z4 * (1) / 2,
        (α) -> z5 * (-1) / 2 + z6 * (1) / 2,
        (α) -> z7 * (-1) / 2 + z8 * (1) / 2]
     
        #Define 6 faces for each x, y and z:
    fx, dfx = blend_edges(ex, dex)
    fy, dfy = blend_edges(ey, dey)
    fz, dfz = blend_edges(ez, dez)


    # x(q, r, s), xq(q, r, s), xr(q, r, s), xs(q, r, s) = transfinite_blend_3Dcomp(fx, ex, q, r, s)
