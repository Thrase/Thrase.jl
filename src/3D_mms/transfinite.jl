        (α) -> x2 * (-1) / 2 + x4 * (1) / 2,
        (α) -> x5 * (-1) / 2 + x7 * (1) / 2,
        (α) -> x6 * (-1) / 2 + x8 * (1) / 2,

        (α) -> x1 * (-1) / 2 + x2 * (1) / 2,
        (α) -> x3 * (-1) / 2 + x4 * (1) / 2,
        (α) -> x5 * (-1) / 2 + x6 * (1) / 2,
        (α) -> x7 * (-1) / 2 + x8 * (1) / 2]

  ey = [(α) -> y1 * (1 .- α) / 2 + y5 * (1 .+ α) / 2,
        (α) -> y2 * (1 .- α) / 2 + y6 * (1 .+ α) / 2,
        (α) -> y3 * (1 .- α) / 2 + y7 * (1 .+ α) / 2,
        (α) -> y4 * (1 .- α) / 2 + y8 * (1 .+ α) / 2,

        (α) -> y1 * (1 .- α) / 2 + y3 * (1 .+ α) / 2,
        (α) -> y2 * (1 .- α) / 2 + y4 * (1 .+ α) / 2,
        (α) -> y5 * (1 .- α) / 2 + y7 * (1 .+ α) / 2,
        (α) -> y6 * (1 .- α) / 2 + y8 * (1 .+ α) / 2,

        (α) -> y1 * (1 .- α) / 2 + y2 * (1 .+ α) / 2,
        (α) -> y3 * (1 .- α) / 2 + y4 * (1 .+ α) / 2,
        (α) -> y5 * (1 .- α) / 2 + y6 * (1 .+ α) / 2,
        (α) -> y7 * (1 .- α) / 2 + y8 * (1 .+ α) / 2]

  dey = [(α) -> y1 * (-1) / 2 + y5 * (1) / 2,
        (α) -> y2 * (-1) / 2 + y6 * (1) / 2,
        (α) -> y3 * (-1) / 2 + y7 * (1) / 2,
        (α) -> y4 * (-1) / 2 + y8 * (1) / 2,

        (α) -> y1 * (-1) / 2 + y3 * (1) / 2,
        (α) -> y2 * (-1) / 2 + y4 * (1) / 2,
        (α) -> y5 * (-1) / 2 + y7 * (1) / 2,
        (α) -> y6 * (-1) / 2 + y8 * (1) / 2,

        (α) -> y1 * (-1) / 2 + y2 * (1) / 2,
        (α) -> y3 * (-1) / 2 + y4 * (1) / 2,
        (α) -> y5 * (-1) / 2 + y6 * (1) / 2,
        (α) -> y7 * (-1) / 2 + y8 * (1) / 2]

  ez = [(α) -> z1 * (1 .- α) / 2 + z5 * (1 .+ α) / 2,
        (α) -> z2 * (1 .- α) / 2 + z6 * (1 .+ α) / 2,
        (α) -> z3 * (1 .- α) / 2 + z7 * (1 .+ α) / 2,
        (α) -> z4 * (1 .- α) / 2 + z8 * (1 .+ α) / 2,

        (α) -> z1 * (1 .- α) / 2 + z3 * (1 .+ α) / 2,
        (α) -> z2 * (1 .- α) / 2 + z4 * (1 .+ α) / 2,
